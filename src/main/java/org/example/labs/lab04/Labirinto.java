    private int linhaInicial = 4;
    private int colunaInicial = 0;
    private int linhaFinal = 21;
    private int colunaFinal = 49;

    private Pilha<Posicao> pilha = new Pilha<>(mapa.length * mapa[0].length);

    private boolean[][] visitados = new boolean[mapa.length][mapa[0].length];


    private boolean posicaoValida(int linha, int coluna) {

        if (linha < 0 || linha >= mapa.length || coluna < 0 || coluna >= mapa[linha].length) {
            return false;
        }

        if (mapa[linha][coluna] == '*') {
            return false;
        }

        if (visitados[linha][coluna]) {
            return false;
        }

        return true;
    }

    private void marcarCaminho() {

        while (!pilha.isEmpty()) {

            Posicao posicao = pilha.pop();

            int linha = posicao.getLinha();
            int coluna = posicao.getColuna();

            if (mapa[linha][coluna] != 'P'
                    && mapa[linha][coluna] != 'T') {

                mapa[linha][coluna] = '+';
            }
        }
    }

    public boolean jogar() {

        Posicao inicio = new Posicao(linhaInicial, colunaInicial);

        pilha.push(inicio);
        visitados[linhaInicial][colunaInicial] = true;

        while (!pilha.isEmpty()) {

            Posicao atual = pilha.peek();

            int linha = atual.getLinha();
            int coluna = atual.getColuna();

            // Chegou no destino
            if (linha == linhaFinal && coluna == colunaFinal) {
                marcarCaminho();
                return true;
            }

            // cima
            if (posicaoValida(linha - 1, coluna)) {

                pilha.push(new Posicao(linha - 1, coluna));
                visitados[linha - 1][coluna] = true;

            }

            // baixo
            else if (posicaoValida(linha + 1, coluna)) {

                pilha.push(new Posicao(linha + 1, coluna));
                visitados[linha + 1][coluna] = true;

            }

            // esquerda
            else if (posicaoValida(linha, coluna - 1)) {

                pilha.push(new Posicao(linha, coluna - 1));
                visitados[linha][coluna - 1] = true;

            }

            // direita
            else if (posicaoValida(linha, coluna + 1)) {

                pilha.push(new Posicao(linha, coluna + 1));
                visitados[linha][coluna + 1] = true;

            }

            // nenhum caminho disponível
            else {
                pilha.pop();
            }
        }

        return false;
    }

    public void imprimir() {
        for (int i = 4; i < mapa.length; i++) {
            for (int j = 0; j < mapa[i].length; j++) {
                System.out.print(mapa[i][j]);
            }
            System.out.println();
        }
    }


    public static void main(String[] args) {

        Labirinto labirinto = new Labirinto();

        System.out.println("Labirinto original:");
        labirinto.imprimir();

        boolean encontrou = labirinto.jogar();

        System.out.println();

        if (encontrou) {
            System.out.println("Caminho encontrado!");
            labirinto.imprimir();
        } else {
            System.out.println("Nenhum caminho encontrado.");
        }
    }
